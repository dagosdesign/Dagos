/* WORD PATH — the semantic connection database.
 *
 * WORD PATH is a semantic vocabulary game, not a sequence game. Every path is a
 * set of words held together by ONE language relationship — synonymy, near
 * meaning, category membership or a single clear lexical field. The player picks
 * the word that belongs to the same group, never the word that "happens next".
 *
 * Cause and effect, processes, routines, chronologies and story logic are not
 * allowed here and no entry in this file uses them.
 *
 * words       members of the group. Three become the path, a fourth is the answer.
 * distractors words associated with the topic that are NOT members of the group,
 *             so exactly one option can ever be right.
 * predicate   completes "X, Y and Z are …" in the explanation.
 */

